import { Column, Entity, PrimaryGeneratedColumn } from 'typeorm';
import { DishCategory } from './enums/dish-category.enum.js';

@Entity('dishes')
export class Dish {
    @PrimaryGeneratedColumn({ name: 'id' })
    id: number;

    @Column({ name: 'name', nullable: false, unique: true })
    name: string;

    @Column({ name: 'description', nullable: false, unique: false })
    description: string;

    @Column({
        name: 'price',
        type: 'decimal',
        precision: 10,
        scale: 2,
        nullable: false,
        unique: false,
    })
    price: number;

    @Column({
        name: 'category',
        type: 'enum',
        enum: DishCategory,
        nullable: false,
        unique: false,
    })
    category: DishCategory;

    @Column({ name: 'available', nullable: false, unique: false, default: true })
    available: boolean;
}

